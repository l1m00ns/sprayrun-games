// Diagnostic: when does GET /api/me return 401 during the duel flow? (steps are timestamped next to the requests)
import { startServer, launch } from './lib.mjs';
const srv = await startServer(3700 + Math.floor(Math.random() * 50), { AI_DISABLED: '1' });
const browser = await launch(900, 560);
const page = await browser.newPage();
const t0 = Date.now();
const log = (s) => console.log(String(Date.now() - t0).padStart(7), s);
page.on('response', (r) => { if (r.url().includes('/api/')) log(`${r.request().method().padEnd(5)} ${r.status()} ${r.url().replace(/^http:\/\/localhost:\d+/, '')} auth=${!!r.request().headers()['authorization']}`); });
await page.evaluateOnNewDocument(() => { try { localStorage.setItem('sprayrun.save.v1', JSON.stringify({ settings: { quality: 'low', weather: false, music: 0, sfx: 0, lang: 'en' }, onboarded: true })); } catch (e) { /* noop */ } });
await page.goto(srv.url, { waitUntil: 'load' });
await page.waitForFunction(() => window.__game && window.__game.state === 'menu', { timeout: 180000 });
log('STEP menu ready');
await new Promise((r) => setTimeout(r, 2500));
log('STEP enterArena');
await page.evaluate(() => { window.__game.cheats.duelBot = 'dummy'; window.__game.enterArena({ online: false }); });
await new Promise((r) => setTimeout(r, 2500));
log('STEP stop arena');
await page.evaluate(() => window.__game.duelCtl.stop());
await page.evaluate(() => { const g = window.__game; g.save.tutorialDone = true; g.startSoloDuelRun(); });
log('STEP solo duel run started');
await new Promise((r) => setTimeout(r, 6000));
log('STEP end');
await browser.close(); srv.stop(); process.exit(0);
